"""Faithful Python port of the ORIGINAL scripts, bugs included, for validation.

    python tools/original_port.py      -> results/original_comparison.md

Part A ports legacy/kalman_26_sep.m (final synthetic test) and runs it on the
same stored noise as the corrected pipeline, so differences are due to the
code changes only. Part B ports legacy/random_noise_attenuation.m, whose
figure titles are the only original numbers that were written down.
Reproduced original behaviour:
  * hyperbolic_events: frequency-domain synthesis with a truncated Ricker and
    an extra band-limited noise term (snr = 1000, L = 1000);
  * f-x decon called with dt = 0.001 s although the data are sampled at 2 ms;
  * Kalman1D: output sample 1 fixed to 0 (no update on the first sample);
  * SNR = 10 log10(sum(out^2) / sum((out - clean)^2)).
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from scipy.signal import convolve2d

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from kalman_denoise.baselines import fx_decon, savgol_filter, svd_denoise  # noqa: E402
from kalman_denoise.io import load_config, load_noise  # noqa: E402
from kalman_denoise.metrics import snr_db, snr_db_original  # noqa: E402
from kalman_denoise.pipeline import run_synthetic  # noqa: E402


def ricker_seismiclab(f, dt):
    nw = 2 * int(np.floor(2.2 / f / dt / 2)) + 1
    nc = nw // 2
    i = np.arange(1, nw + 1)
    b = ((nc - i + 1) * f * dt * np.pi) ** 2
    return (1 - 2 * b) * np.exp(-b)


def hyperbolic_events_original(dt, f0, tmax, h, tau, v, amp, snr, L, rng):
    nt = int(np.floor(tmax / dt)) + 1
    nfft = 4 * 2 ** int(np.ceil(np.log2(nt)))
    w = ricker_seismiclab(f0, dt)
    W = np.fft.fft(w, nfft)
    delay = dt * (w.size // 2 + 1)
    D = np.zeros((nfft, h.size), complex)
    for k in range(nfft // 2 + 1):
        om = 2 * np.pi * k / nfft / dt
        for j in range(len(tau)):
            D[k] += amp[j] * W[k] * np.exp(-1j * om * (np.sqrt(tau[j] ** 2 + (h / v[j]) ** 2) - delay))
    for k in range(1, nfft // 2):
        D[nfft - k] = np.conj(D[k])
    d = np.real(np.fft.ifft(D, axis=0))[:nt]
    op = np.hamming(L)
    op /= op.sum()
    noise = convolve2d(rng.standard_normal(d.shape), op[:, None], mode="same")
    return d + d.max() / snr * noise


def kalman1d_original(X, Q, R=0.05):
    Y = np.zeros(X.size)
    P = 1.01
    for i in range(1, X.size):
        Pt = P + Q
        K = Pt / (Pt + R)
        Y[i] = Y[i - 1] + K * (X[i] - Y[i - 1])
        P = (1 - K) * Pt
    return Y


def part_a(cfg):
    rng = np.random.default_rng(0)
    s = cfg["synthetic"]
    h = np.arange(20, 1001, 20.0)
    d = hyperbolic_events_original(0.002, 20, 3, h, s["tau_s"], s["v_mps"], s["amp"], 1000, 1000, rng)
    clean_orig = np.hstack([d[:, ::-1], d])
    unit = load_noise(cfg["noise"]["file"])
    rows = []
    for sigma in cfg["noise"]["sigma_levels"]:
        noisy = clean_orig + sigma * unit
        outs = {
            "Savitzky-Golay": savgol_filter(noisy, 4, 27),
            "f-x decon": fx_decon(noisy, 0.001, 8, 0.0, 0.0, 200.0),
            "SVD": svd_denoise(noisy, 18),
            "Kalman": np.column_stack([kalman1d_original(noisy[:, j], 0.004) for j in range(noisy.shape[1])]),
        }
        new = run_synthetic(cfg, sigma)
        rows.append((sigma, snr_db(clean_orig, noisy), new["snr"]["input"], {
            m: (snr_db_original(clean_orig, e), snr_db(clean_orig, e), new["snr"][m]) for m, e in outs.items()}))
    return rows


def part_b():
    vals = {k: [] for k in ("noisy", "Savitzky-Golay", "f-x decon", "SVD", "Kalman")}
    for seed in range(5):
        rng = np.random.default_rng(100 + seed)
        A1 = 5 * hyperbolic_events_original(0.001, 25, 5, np.arange(0, 501, 5.0), [.5, 1.5, 2],
                                            [400, 420, 440], [5, -5, 5], 1000, 1000, rng)
        y = 0.08 * rng.standard_normal(A1.shape)
        A2 = A1 + y
        vals["noisy"].append(10 * np.log10(np.sum(A1 ** 2) / np.sum(y ** 2)))
        vals["Savitzky-Golay"].append(snr_db_original(A1, savgol_filter(A2, 4, 31)))
        vals["f-x decon"].append(snr_db_original(A1, fx_decon(A2, 0.001, 4, 1.0, 1.0, 500.0)))
        vals["SVD"].append(snr_db(A1, svd_denoise(A2, 50)))  # this one used the clean signal
        xf = np.column_stack([kalman1d_original(A2[:, j], 0.005) for j in range(A2.shape[1])])
        vals["Kalman"].append(snr_db_original(A1, xf))
    return {k: (float(np.mean(v)), float(np.std(v))) for k, v in vals.items()}


def main():
    cfg = load_config()
    lines = ["# Comparison with the original code", "",
             "Generated by `tools/original_port.py`.", "",
             "## A. Final synthetic test (`legacy/kalman_26_sep.m`)", "",
             "Same stored noise for both codes. *Original code* = faithful port incl. its bugs; "
             "*corrected* = this repository.", "",
             "| σ | Method | original code, original SNR formula | original code, correct SNR | corrected code |",
             "|---|---|---:|---:|---:|"]
    for sigma, in_o, in_n, d in part_a(cfg):
        lines.append(f"| {sigma:g} | Input | {in_o:.2f} | {in_o:.2f} | {in_n:.2f} |")
        for m, (a, b, c) in d.items():
            lines.append(f"| {sigma:g} | {m} | {a:.2f} | {b:.2f} | {c:.2f} |")
    b = part_b()
    titles = {"noisy": 4, "Savitzky-Golay": 13, "f-x decon": 10, "SVD": 6, "Kalman": 7}
    lines += ["", "## B. Numbers written in the original figure titles (`legacy/random_noise_attenuation.m`)", "",
              "Mean ± std over 5 noise realisations, computed exactly as in the script.", "",
              "| Quantity | value in original title | faithful port |", "|---|---:|---:|"]
    for k, (mu, sd) in b.items():
        lines.append(f"| {k} | {titles[k]} | {mu:.2f} ± {sd:.2f} |")
    text = "\n".join(lines) + "\n"
    (ROOT / "results" / "original_comparison.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
